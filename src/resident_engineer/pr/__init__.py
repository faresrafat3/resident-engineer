"""Proof-Carrying PR — every PR carries its evidence."""
from __future__ import annotations
from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
from typing import Any


class PRStatus(str, Enum):
    DRAFT = "draft"
    READY = "ready"
    SUBMITTED = "submitted"
    MERGED = "merged"
    REJECTED = "rejected"


@dataclass
class Evidence:
    type: str
    description: str
    data: dict[str, Any]
    verified: bool = False


@dataclass
class ProofCarryingPR:
    """A PR that carries all its evidence."""

    number: int | None
    title: str
    description: str
    project: str
    branch: str
    base_branch: str = "main"
    files_changed: list[str] = field(default_factory=list)
    tests_added: list[str] = field(default_factory=list)
    evidence: list[Evidence] = field(default_factory=list)
    risks: list[str] = field(default_factory=list)
    rationale: str = ""
    status: PRStatus = PRStatus.DRAFT
    created_at: datetime = field(default_factory=datetime.now)
    url: str | None = None

    def add_evidence(self, evidence: Evidence) -> None:
        self.evidence.append(evidence)

    def is_ready(self) -> bool:
        return all(e.verified for e in self.evidence) and len(self.evidence) > 0

    def to_body(self) -> str:
        lines = [f"## {self.title}", "", self.description, "", "## Rationale", self.rationale, "", "## Changes"]
        for f in self.files_changed:
            lines.append(f"- `{f}`")
        lines.append("")
        if self.tests_added:
            lines.append("## Tests")
            for t in self.tests_added:
                lines.append(f"- {t}")
            lines.append("")
        if self.evidence:
            lines.append("## Evidence")
            for e in self.evidence:
                status = "✅" if e.verified else "⏳"
                lines.append(f"- {status} **{e.type}**: {e.description}")
            lines.append("")
        if self.risks:
            lines.append("## Risks")
            for r in self.risks:
                lines.append(f"- ⚠️ {r}")
            lines.append("")
        lines.append("---")
        lines.append("*Generated by Resident Engineering System*")
        return "\n".join(lines)

    def to_dict(self) -> dict[str, Any]:
        return {
            "number": self.number, "title": self.title, "description": self.description,
            "project": self.project, "branch": self.branch, "base_branch": self.base_branch,
            "files_changed": self.files_changed, "tests_added": self.tests_added,
            "evidence": [{"type": e.type, "description": e.description, "data": e.data, "verified": e.verified} for e in self.evidence],
            "risks": self.risks, "rationale": self.rationale, "status": self.status.value,
            "created_at": self.created_at.isoformat(), "url": self.url,
        }
